import XCTest

@MainActor
final class MatchNavigationUITests: ScoreboardUITestCase {
    func testHomeWorkspaceTabsStayInMainWindow() {
        launch("setup", opensBoard: false)
        tap(app.buttons["home.new"])
        XCTAssertTrue(app.textFields["home.newName"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.sheets.count, 0)
        capture("New Scoreboard tab in the main workspace")
        tap(app.buttons["home.cancelNew"])
        XCTAssertTrue(app.buttons["home.open"].waitForExistence(timeout: 5))
        tap(app.buttons["home.connect"])
        XCTAssertTrue(app.textFields["join.matchCode"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.textFields["join.server"].exists)
        XCTAssertEqual(app.sheets.count, 0)
        capture("Connect tab with a single code and link form")
        tap(app.buttons["home.tab.open"])
        XCTAssertTrue(app.buttons["home.open"].waitForExistence(timeout: 5))
    }
    func testNewScoreboardSharedLayout() {
        launch("setup", opensBoard: false)
        tap(app.buttons["home.new"])
        let name = app.textFields["home.newName"]
        XCTAssertTrue(name.waitForExistence(timeout: 5))
        XCTAssertTrue(app.buttons["home.newSport.simple"].isHittable)
        XCTAssertTrue(app.buttons["home.newSport.basketball"].isHittable)
        XCTAssertTrue(app.buttons["home.cancelNew"].isHittable)
        XCTAssertTrue(app.buttons["home.create"].isHittable)
        tap(app.buttons["home.newSport.basketball"])
        XCTAssertTrue(app.buttons["home.newSport.basketball"].isSelected)
        capture("Shared New Scoreboard sport selection")
        tap(name); name.typeText("Court One")
        capture("Shared New Scoreboard layout")
        tap(app.buttons["home.create"])
        XCTAssertTrue(app.staticTexts["settings.title.game"].waitForExistence(timeout: 10))
    }

    func testUnifiedConnectionManagerEntryPoints() {
        launch()
        tap(app.buttons["connection.statusButton"])
        XCTAssertTrue(app.scrollViews["connection.status"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Session Host"].exists)
        XCTAssertTrue(app.staticTexts["Owner"].exists)
        XCTAssertTrue(app.switches["host.nearby"].isHittable, "Pairing stays reachable beneath the empty status/roster")
        capture("Unified device manager layout")
        tap(app.buttons["connection.done"])
        tap(mainWindow.buttons["Settings"].firstMatch)
        tapMenuAction("Connect Devices")
        XCTAssertTrue(app.scrollViews["connection.status"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.switches["host.nearby"].isHittable)
        tap(app.buttons["connection.done"])
        XCTAssertTrue(app.buttons["connection.statusButton"].isHittable)
    }

    func testFileHomeSeparateSettingsAndKioskNavigation() {
        executionTimeAllowance = 180
        launch("setup", opensBoard: false)
        XCTAssertTrue(app.buttons["home.new"].waitForExistence(timeout: 10))
        XCTAssertTrue(app.buttons["home.open"].exists)
        XCTAssertEqual(app.buttons.matching(identifier: "home.open").count, 1)
        XCTAssertEqual(app.buttons["home.open"].label, "Open File…")
        XCTAssertFalse(app.staticTexts["On This Device"].exists)
        XCTAssertTrue(app.buttons["home.connect"].exists)
        XCTAssertFalse(app.buttons["home.continue"].exists)
        XCTAssertTrue(app.staticTexts["home.version"].exists)
        XCTAssertTrue(app.staticTexts["home.version"].label.contains("Build"))
        XCTAssertEqual(app.staticTexts["home.cloudStatus"].label, "Cloud · Off")
        capture("File Home before creating a scoreboard")

        tap(app.buttons["home.new"])
        let name = app.textFields["home.newName"]
        XCTAssertTrue(name.waitForExistence(timeout: 5))
        tap(app.buttons["home.create"])
        XCTAssertTrue(app.staticTexts["settings.title.game"].waitForExistence(timeout: 10))
        XCTAssertFalse(app.buttons["settings.pane.cloud"].exists)
        XCTAssertFalse(app.buttons["settings.pane.sound"].exists)
        capture("Game Settings contain only file settings")
        returnToBoard()
        addScore(1)
        XCTAssertEqual(text(score()), "1")

        tap(app.buttons["connection.statusButton"])
        XCTAssertTrue(app.scrollViews["connection.status"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Session Host"].exists)
        XCTAssertTrue(app.staticTexts["Owner"].exists)
        XCTAssertTrue(app.switches["host.nearby"].exists)
        capture("Unified connection status and device manager from badge")
        tap(app.buttons["connection.done"])

        openAppSettings()
        XCTAssertEqual(app.sheets.count, 0, "App Settings uses the full workspace")
        XCTAssertTrue(app.staticTexts["settings.title.general"].exists)
        XCTAssertFalse(app.buttons["settings.pane.game"].exists)
        XCTAssertFalse(app.buttons["settings.pane.remoteDisplay"].exists)
        selectSettingsSection("cloud")
        XCTAssertTrue(app.staticTexts["settings.title.cloud"].exists)
        let enableCloud = app.switches["Enable Cloud"].firstMatch
        XCTAssertTrue(enableCloud.waitForExistence(timeout: 5))
        tap(enableCloud)
        capture("Separate App Settings")
        returnToBoard()
        tap(mainWindow.buttons["Settings"].firstMatch)
        tapMenuAction("Connect Devices")
        XCTAssertTrue(app.scrollViews["connection.status"].waitForExistence(timeout: 5))
        XCTAssertTrue(app.staticTexts["Session Host"].exists)
        tap(app.buttons["LAN & Cloud Settings"])
        XCTAssertTrue(app.staticTexts["settings.title.cloud"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.sheets.count, 0, "Settings opened from Connect Devices also fills the workspace")
        returnToBoard()
        XCTAssertEqual(text(score()), "1")
        goHome()
        XCTAssertTrue(app.buttons["home.continue"].waitForExistence(timeout: 5))
        XCTAssertEqual(app.staticTexts["home.cloudStatus"].label, "Cloud · Not Signed In")
        capture("File Home with a saved scoreboard")

        tap(app.buttons["home.settings"])
        tap(app.buttons["LAN & Cloud"].firstMatch)
        XCTAssertTrue(app.staticTexts["settings.title.cloud"].waitForExistence(timeout: 5))
        tap(app.switches["connections.localEnabled"])
        XCTAssertTrue(app.switches["Enable Cloud"].exists)
        XCTAssertEqual(app.staticTexts["connections.preference"].label, "Cloud Only")
        capture("Full-screen LAN and Cloud settings in Cloud Only mode")
        returnToBoard()
        XCTAssertTrue(app.buttons["home.connect"].isEnabled)
        tap(app.buttons["home.connect"])
        XCTAssertTrue(app.textFields["join.matchCode"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.staticTexts["Nearby Matches"].exists)
        tap(app.buttons["home.tab.open"])
        tap(app.buttons["home.settings"])
        tap(app.buttons["LAN & Cloud"].firstMatch)
        tap(app.switches["Enable Cloud"])
        returnToBoard()
        XCTAssertTrue(app.buttons["home.connect"].isEnabled, "The Connect tab remains available for configuring connections")
        XCTAssertEqual(app.staticTexts["home.cloudStatus"].label, "Local Only")
        tap(app.buttons["home.continue"])
        XCTAssertEqual(text(score()), "1")
        goHome()
        tap(app.buttons["home.settings"])
        tap(app.buttons["LAN & Cloud"].firstMatch)
        tap(app.switches["connections.localEnabled"])
        tap(app.switches["Enable Cloud"])
        returnToBoard()
        XCTAssertTrue(app.buttons["home.connect"].isEnabled)
        tap(app.buttons["library.actions"].firstMatch)
        tapMenuAction("Duplicate")
        XCTAssertEqual(app.buttons.matching(identifier: "library.actions").count, 2)

        tap(app.buttons["home.connect"])
        XCTAssertTrue(app.textFields["join.matchCode"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.buttons["join.submit"].isEnabled)
        tap(app.buttons["home.tab.open"])
        tap(app.buttons["home.continue"])
        XCTAssertEqual(text(score()), "1")
        goHome()

        tap(app.buttons["home.settings"])
        tapMenuAction("Switch to Kiosk Mode")
        let change = app.buttons["Use Kiosk Mode"].firstMatch
        XCTAssertTrue(change.waitForExistence(timeout: 5))
        change.tap()
        XCTAssertTrue(app.staticTexts["kiosk.mode"].waitForExistence(timeout: 10))
        XCTAssertEqual(app.staticTexts["kiosk.mode"].label, "iPad · Kiosk Mode")
        XCTAssertTrue(app.staticTexts["home.version"].exists)
        XCTAssertEqual(app.staticTexts["home.cloudStatus"].label, "Cloud · Ready to Join")
        XCTAssertFalse(app.buttons["home.new"].exists)
        capture("Shared iPad kiosk home")
        tap(app.buttons["tv.cloud"])
        XCTAssertTrue(app.textFields["join.matchCode"].waitForExistence(timeout: 5))
        XCTAssertFalse(app.textFields["join.server"].exists, "Kiosk joins use the server configured in App Settings")
        app.navigationBars.buttons.element(boundBy: 0).tap()
        XCTAssertTrue(app.staticTexts["kiosk.mode"].waitForExistence(timeout: 5))
        tap(app.buttons["tv.settings"])
        XCTAssertTrue(app.buttons["remote.cloud.selfHosted"].waitForExistence(timeout: 5))
        tap(app.buttons["remote.cloud.selfHosted"])
        XCTAssertTrue(app.textFields["remote.cloud.selfHostedURL"].waitForExistence(timeout: 5))
        app.navigationBars.buttons.element(boundBy: 0).tap()
        XCTAssertTrue(app.staticTexts["kiosk.mode"].waitForExistence(timeout: 5))
    }

    private func goHome() {
        tap(mainWindow.buttons["Settings"].firstMatch)
        tapMenuAction("Home")
    }

    private func capture(_ name: String) {
        let attachment = XCTAttachment(screenshot: mainWindow.screenshot())
        attachment.name = name; attachment.lifetime = .keepAlways; add(attachment)
    }
}
